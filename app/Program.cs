// Windows Toolbox — portable WebView2 shell around index.html.
// Everything (page, WebView2 SDK, loader) is embedded; at startup it is unpacked
// to %LOCALAPPDATA%\WindowsToolbox. Requires the WebView2 Runtime (built into Windows 11).
//
// Remote update: the page is re-downloaded from the GitHub Pages site on every launch (in the
// background). If it changed, it is cached and the window reloads, so catalog edits reach
// everyone without a new exe. Offline, the last cached (or embedded) page is used.
//
// Self-update: the latest release of this repo is checked on start; a newer exe is
// downloaded, verified and swapped in when the app closes (or on "Restart now").
//
// Host bridge (page ⇄ exe, JSON over WebView2 messages): the page asks for a winget scan and
// installs; every install is confirmed in a native dialog the page cannot fake.
// AppInfo (version, repo, page URL) is generated by build.ps1.
using System;
using System.Collections;
using System.Collections.Generic;
using System.Diagnostics;
using System.Drawing;
using System.IO;
using System.Linq;
using System.Net;
using System.Reflection;
using System.Runtime.CompilerServices;
using System.Runtime.InteropServices;
using System.Security.Cryptography.X509Certificates;
using System.Text;
using System.Text.RegularExpressions;
using System.Threading.Tasks;
using System.Web.Script.Serialization;
using System.Windows.Forms;
using Microsoft.Web.WebView2.Core;
using Microsoft.Web.WebView2.WinForms;

static class Program
{
    public static readonly string Dir = Path.Combine(
        Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData), "WindowsToolbox");
    public static string SiteDir { get { return Path.Combine(Dir, "site"); } }
    public static string ActivePage { get { return Path.Combine(SiteDir, "index.html"); } }
    public static string RemoteCache { get { return Path.Combine(Dir, "remote.html"); } }
    public const string PageMarker = "windows-toolbox-page";

    [STAThread]
    static void Main()
    {
        // WebView2 managed assemblies live inside this exe as resources.
        AppDomain.CurrentDomain.AssemblyResolve += (s, e) =>
        {
            string name = new AssemblyName(e.Name).Name + ".dll";
            byte[] data = ReadResource(name);
            return data == null ? null : Assembly.Load(data);
        };

        Application.EnableVisualStyles();
        Application.SetCompatibleTextRenderingDefault(false);
        ServicePointManager.SecurityProtocol |= SecurityProtocolType.Tls12;

        Directory.CreateDirectory(SiteDir);
        WriteIfChanged(Path.Combine(Dir, "WebView2Loader.dll"), ReadResource("WebView2Loader.dll"));

        // Show the newer of the page embedded at build time and the last one downloaded from the repo
        // (after an exe update the embedded page can be newer than an old cache).
        byte[] page = ReadResource("index.html"), cached = null;
        try { if (File.Exists(RemoteCache)) cached = File.ReadAllBytes(RemoteCache); } catch { }
        if (IsValidPage(cached) && string.CompareOrdinal(BuiltStamp(cached), BuiltStamp(page)) >= 0) page = cached;
        WriteIfChanged(ActivePage, page);

        Run();
    }

    // Kept separate so WebView2 types are resolved only after AssemblyResolve is hooked.
    [MethodImpl(MethodImplOptions.NoInlining)]
    static void Run()
    {
        Application.Run(new MainForm());
    }

    public static bool IsValidPage(byte[] data)
    {
        if (data == null || data.Length < 10000) return false;
        string head = Encoding.UTF8.GetString(data, 0, Math.Min(data.Length, 600));
        return head.Contains(PageMarker);
    }

    // "<!-- windows-toolbox-page built=2026-10-03T12:00:00Z -->" → "2026-10-03T12:00:00Z" ("" if absent)
    public static string BuiltStamp(byte[] data)
    {
        if (data == null) return "";
        Match m = Regex.Match(Encoding.UTF8.GetString(data, 0, Math.Min(data.Length, 600)), PageMarker + @" built=(\S+)");
        return m.Success ? m.Groups[1].Value : "";
    }

    public static byte[] ReadResource(string name)
    {
        using (Stream st = Assembly.GetExecutingAssembly().GetManifestResourceStream(name))
        {
            if (st == null) return null;
            byte[] buf = new byte[st.Length];
            int read = 0;
            while (read < buf.Length) read += st.Read(buf, read, buf.Length - read);
            return buf;
        }
    }

    public static bool SameBytes(byte[] a, byte[] b)
    {
        if (a == null || b == null || a.Length != b.Length) return false;
        for (int i = 0; i < a.Length; i++) if (a[i] != b[i]) return false;
        return true;
    }

    // Returns true when the file was (re)written.
    public static bool WriteIfChanged(string path, byte[] data)
    {
        try
        {
            if (File.Exists(path) && SameBytes(File.ReadAllBytes(path), data)) return false;
            File.WriteAllBytes(path, data);
            return true;
        }
        catch (IOException) { return false; } // in use by another running instance
    }

    public static WebClient NewClient()
    {
        WebClient wc = new WebClient();
        wc.Headers[HttpRequestHeader.UserAgent] = "WindowsToolbox/" + AppInfo.Version;
        return wc;
    }

    // "v1.2.3" / "1.2.3-dev" → 1.2.3
    public static Version ParseVersion(string s)
    {
        Match m = Regex.Match(s ?? "", @"(\d+)(?:\.(\d+))?(?:\.(\d+))?");
        if (!m.Success) return new Version(0, 0, 0);
        Func<int, int> g = i => m.Groups[i].Success ? int.Parse(m.Groups[i].Value) : 0;
        return new Version(g(1), g(2), g(3));
    }
}

class MainForm : Form
{
    const string Host = "toolbox.local";
    static readonly Regex WingetId = new Regex(@"^[A-Za-z0-9][A-Za-z0-9.+_-]*\.[A-Za-z0-9.+_-]+$");
    readonly WebView2 web;
    readonly JavaScriptSerializer json = new JavaScriptSerializer { MaxJsonLength = int.MaxValue };
    string lang = "en";

    // winget
    bool? wingetAvailable;
    string lastInstalled, lastUpgrades;
    bool scanning;
    Task installQueue = Task.FromResult(0);

    // self-update: state is "none" | "downloading" | "ready" | "available" (manual download)
    string updState = "none", updVersion, updUrl, updPath;
    bool updApplied;

    [DllImport("dwmapi.dll")]
    static extern int DwmSetWindowAttribute(IntPtr hwnd, int attr, ref int value, int size);

    public MainForm()
    {
        Text = "Windows Toolbox " + AppInfo.Version;
        Icon = Icon.ExtractAssociatedIcon(Application.ExecutablePath);
        StartPosition = FormStartPosition.CenterScreen;
        Rectangle wa = Screen.PrimaryScreen.WorkingArea;
        Size = new Size(Math.Min(1440, wa.Width - 80), Math.Min(920, wa.Height - 60));
        MinimumSize = new Size(480, 480);
        BackColor = Color.FromArgb(7, 8, 15);

        web = new WebView2();
        web.Dock = DockStyle.Fill;
        web.DefaultBackgroundColor = BackColor;
        Controls.Add(web);

        HandleCreated += (s, e) => UseDarkTitleBar();
        Load += async (s, e) => await InitAsync();
        FormClosing += (s, e) => { if (updState == "ready" && !updApplied) ApplyUpdate(false); };
    }

    void UseDarkTitleBar()
    {
        int dark = 1;
        try
        {
            object v = Microsoft.Win32.Registry.GetValue(
                @"HKEY_CURRENT_USER\Software\Microsoft\Windows\CurrentVersion\Themes\Personalize", "AppsUseLightTheme", 0);
            if (v is int && (int)v == 1) dark = 0;
            DwmSetWindowAttribute(Handle, 20, ref dark, sizeof(int)); // DWMWA_USE_IMMERSIVE_DARK_MODE
        }
        catch { }
    }

    string StartUrl
    {
        get { return "https://" + Host + "/index.html?host=2&appv=" + Uri.EscapeDataString(AppInfo.Version); }
    }

    async Task InitAsync()
    {
        try
        {
            CoreWebView2Environment.SetLoaderDllFolderPath(Program.Dir);
            CoreWebView2Environment env = await CoreWebView2Environment.CreateAsync(null, Path.Combine(Program.Dir, "profile"));
            await web.EnsureCoreWebView2Async(env);
            CoreWebView2 cw = web.CoreWebView2;

            cw.SetVirtualHostNameToFolderMapping(Host, Program.SiteDir, CoreWebView2HostResourceAccessKind.Allow);
            cw.Settings.AreDevToolsEnabled = false;
            cw.Settings.IsStatusBarEnabled = false;
            cw.Settings.AreBrowserAcceleratorKeysEnabled = false;

            // Links with target=_blank (GitHub pages, project sites) open in the user's browser.
            cw.NewWindowRequested += (s, e) => { e.Handled = true; OpenExternal(e.Uri); };
            // A plain link navigating the main frame away from the app also goes to the browser;
            // downloads and blob:/data: URLs (export, .ps1) are let through.
            cw.NavigationStarting += (s, e) =>
            {
                Uri u;
                if (Uri.TryCreate(e.Uri, UriKind.Absolute, out u) &&
                    (u.Scheme == Uri.UriSchemeHttp || u.Scheme == Uri.UriSchemeHttps) &&
                    u.Host != Host && !IsDownload(u))
                {
                    e.Cancel = true;
                    OpenExternal(e.Uri);
                }
            };
            cw.WebMessageReceived += OnPageMessage;

            cw.Navigate(StartUrl);
            CheckForPageUpdate();
            CheckForAppUpdate();
        }
        catch (Exception ex)
        {
            MessageBox.Show(this,
                "Could not start the WebView2 Runtime:\n" + ex.Message +
                "\n\nThe page will open in your browser instead.\nWebView2 can be installed from Microsoft: https://go.microsoft.com/fwlink/p/?LinkId=2124703",
                "Windows Toolbox", MessageBoxButtons.OK, MessageBoxIcon.Warning);
            OpenExternal(Program.ActivePage);
            Close();
        }
    }

    // ---- page ⇄ exe messages ---------------------------------------------------------------

    void Post(Dictionary<string, object> msg)
    {
        string text = json.Serialize(msg);
        Action a = () => { if (!IsDisposed && web.CoreWebView2 != null) web.CoreWebView2.PostWebMessageAsString(text); };
        if (InvokeRequired) BeginInvoke(a); else a();
    }

    static Dictionary<string, object> Msg(string type, params object[] kv)
    {
        Dictionary<string, object> d = new Dictionary<string, object> { { "type", type } };
        for (int i = 0; i + 1 < kv.Length; i += 2) d[(string)kv[i]] = kv[i + 1];
        return d;
    }

    void OnPageMessage(object sender, CoreWebView2WebMessageReceivedEventArgs e)
    {
        if (!e.Source.StartsWith("https://" + Host + "/", StringComparison.OrdinalIgnoreCase)) return;
        Dictionary<string, object> m;
        try { m = json.Deserialize<Dictionary<string, object>>(e.TryGetWebMessageAsString()); } catch { return; }
        if (m == null || !m.ContainsKey("cmd")) return;
        object l;
        if (m.TryGetValue("lang", out l) && l is string && Regex.IsMatch((string)l, "^(en|uk|ru)$")) lang = (string)l;

        switch (m["cmd"] as string)
        {
            case "ready":   // page (re)loaded: send everything it needs
                SendHelloAndScan();
                PostUpdateState();
                break;
            case "install":
                RequestInstall(m);
                break;
            case "applyUpdate":
                if (updState == "ready") ApplyUpdate(true);
                break;
        }
    }

    // ---- winget ------------------------------------------------------------------------------

    static int RunWinget(string args, out string stdout)
    {
        stdout = "";
        try
        {
            ProcessStartInfo psi = new ProcessStartInfo("winget", args)
            {
                UseShellExecute = false, CreateNoWindow = true,
                RedirectStandardOutput = true, StandardOutputEncoding = Encoding.UTF8
            };
            using (Process p = Process.Start(psi))
            {
                stdout = p.StandardOutput.ReadToEnd();
                p.WaitForExit();
                return p.ExitCode;
            }
        }
        catch { return int.MinValue; } // winget not installed
    }

    async void SendHelloAndScan()
    {
        if (wingetAvailable == null)
        {
            string o;
            wingetAvailable = await Task.Run(() => RunWinget("--version", out o) == 0);
        }
        Post(Msg("hello", "version", AppInfo.Version, "winget", wingetAvailable == true));
        if (wingetAvailable != true) return;
        if (lastInstalled != null) Post(Msg("scan", "installed", lastInstalled, "upgrades", lastUpgrades));
        else Scan();
    }

    async void Scan()
    {
        if (scanning) return;
        scanning = true;
        try
        {
            string[] result = await Task.Run(() =>
            {
                string tmp = Path.Combine(Path.GetTempPath(), "toolbox-winget-" + Guid.NewGuid().ToString("N") + ".json");
                string o, upgrades;
                RunWinget("export -o \"" + tmp + "\" --source winget --accept-source-agreements --disable-interactivity", out o);
                string installed = File.Exists(tmp) ? File.ReadAllText(tmp) : "";
                try { File.Delete(tmp); } catch { }
                RunWinget("upgrade --source winget --accept-source-agreements --disable-interactivity", out upgrades);
                return new[] { installed, upgrades };
            });
            lastInstalled = result[0]; lastUpgrades = result[1];
            Post(Msg("scan", "installed", lastInstalled, "upgrades", lastUpgrades));
        }
        finally { scanning = false; }
    }

    static readonly Dictionary<string, string[]> ConfirmText = new Dictionary<string, string[]>
    {
        { "en", new[] { "Install with winget?", "Installers may ask for administrator rights." } },
        { "uk", new[] { "Встановити через winget?", "Інсталятори можуть запитати права адміністратора." } },
        { "ru", new[] { "Установить через winget?", "Установщики могут запросить права администратора." } },
    };

    void RequestInstall(Dictionary<string, object> m)
    {
        object idsObj, namesObj;
        if (wingetAvailable != true || !m.TryGetValue("ids", out idsObj) || !(idsObj is ArrayList)) return;
        List<string> ids = ((ArrayList)idsObj).OfType<string>().Where(id => WingetId.IsMatch(id)).Distinct().Take(100).ToList();
        List<string> names = m.TryGetValue("names", out namesObj) && namesObj is ArrayList
            ? ((ArrayList)namesObj).OfType<string>().ToList() : new List<string>();
        if (ids.Count == 0) return;

        // Native confirmation: a remote page alone can never start an install.
        StringBuilder list = new StringBuilder();
        for (int i = 0; i < ids.Count && i < 25; i++)
            list.AppendLine("•  " + (i < names.Count ? names[i] + "  (" + ids[i] + ")" : ids[i]));
        if (ids.Count > 25) list.AppendLine("…  +" + (ids.Count - 25));
        string[] t = ConfirmText[ConfirmText.ContainsKey(lang) ? lang : "en"];
        if (MessageBox.Show(this, list + "\n" + t[1], t[0], MessageBoxButtons.OKCancel, MessageBoxIcon.Question) != DialogResult.OK)
        {
            foreach (string id in ids) Post(Msg("progress", "id", id, "state", "cancelled"));
            return;
        }

        foreach (string id in ids)
        {
            string pkg = id;
            installQueue = installQueue.ContinueWith(_ =>
            {
                Post(Msg("progress", "id", pkg, "state", "running"));
                string o;
                // `install` also upgrades a package that is already installed
                int code = RunWinget("install --id " + pkg + " --exact --source winget --silent " +
                                     "--accept-package-agreements --accept-source-agreements --disable-interactivity", out o);
                // 0x8A15002B: already installed, no newer version — that's fine too
                bool ok = code == 0 || code == unchecked((int)0x8A15002B);
                Post(Msg("progress", "id", pkg, "state", ok ? "done" : "error", "code", "0x" + code.ToString("X8")));
            });
        }
        installQueue = installQueue.ContinueWith(_ => BeginInvoke((Action)(() => { lastInstalled = null; Scan(); })));
    }

    // ---- remote page update ----------------------------------------------------------------------

    // Downloads the current page from the repo; if it differs from what is shown, caches it and reloads.
    async void CheckForPageUpdate()
    {
        byte[] fresh = await Task.Run(() =>
        {
            try
            {
                using (WebClient wc = Program.NewClient())
                {
                    wc.Headers[HttpRequestHeader.CacheControl] = "no-cache";
                    return wc.DownloadData(AppInfo.PageUrl + "?t=" + DateTime.UtcNow.Ticks);
                }
            }
            catch { return null; } // offline or GitHub unavailable — keep the current page
        });
        if (!Program.IsValidPage(fresh) || IsDisposed) return;
        byte[] shown = null;
        try { shown = File.ReadAllBytes(Program.ActivePage); } catch { }
        // never go back to an older build (e.g. this exe is newer than what is published yet)
        if (string.CompareOrdinal(Program.BuiltStamp(fresh), Program.BuiltStamp(shown)) < 0) return;

        Program.WriteIfChanged(Program.RemoteCache, fresh);
        if (Program.WriteIfChanged(Program.ActivePage, fresh) && web.CoreWebView2 != null)
            web.CoreWebView2.Navigate(StartUrl);
    }

    // ---- self-update ------------------------------------------------------------------------------

    void PostUpdateState()
    {
        Post(Msg("update", "state", updState, "version", updVersion ?? "", "url", updUrl ?? ""));
    }

    async void CheckForAppUpdate()
    {
        if (AppInfo.Version.Contains("-")) return;   // dev builds don't update themselves
        string exePath = Application.ExecutablePath;
        try
        {
            // {version, url, size}: latest.json on GitHub Pages (no API rate limit), else the GitHub API
            object[] latest = await Task.Run(() => LatestRelease());
            if (latest == null) return;
            string tag = (string)latest[0];
            if (Program.ParseVersion(tag) <= Program.ParseVersion(AppInfo.Version)) return;
            updVersion = tag;
            updUrl = (string)latest[1];
            long size = (long)latest[2];

            if (!CanWriteNextTo(exePath)) { updState = "available"; PostUpdateState(); return; }

            updState = "downloading"; PostUpdateState();
            string dir = Path.Combine(Program.Dir, "update");
            Directory.CreateDirectory(dir);
            updPath = Path.Combine(dir, "WindowsToolbox-" + Regex.Replace(tag, @"[^\w.-]", "") + ".exe");
            if (!File.Exists(updPath) || new FileInfo(updPath).Length != size)
                await Task.Run(() => { using (WebClient wc = Program.NewClient()) wc.DownloadFile(updUrl, updPath); });

            if (!IsTrustedUpdate(updPath, size, tag, exePath))
            {
                try { File.Delete(updPath); } catch { }
                updState = "available"; PostUpdateState();
                return;
            }
            updState = "ready"; PostUpdateState();
        }
        catch { if (updState == "downloading") { updState = "available"; PostUpdateState(); } }
    }

    object[] LatestRelease()
    {
        try
        {
            using (WebClient wc = Program.NewClient())
            {
                Dictionary<string, object> j = json.Deserialize<Dictionary<string, object>>(wc.DownloadString(
                    AppInfo.SiteUrl + "/latest.json?t=" + DateTime.UtcNow.Ticks));
                return new object[] { (string)j["version"], (string)j["url"], Convert.ToInt64(j["size"]) };
            }
        }
        catch { }
        try
        {
            using (WebClient wc = Program.NewClient())
            {
                Dictionary<string, object> rel = json.Deserialize<Dictionary<string, object>>(
                    wc.DownloadString("https://api.github.com/repos/" + AppInfo.Repo + "/releases/latest"));
                Dictionary<string, object> asset = ((ArrayList)rel["assets"]).OfType<Dictionary<string, object>>()
                    .FirstOrDefault(a => ((string)a["name"]).EndsWith(".exe", StringComparison.OrdinalIgnoreCase));
                if (asset == null) return null;
                return new object[] { (string)rel["tag_name"], (string)asset["browser_download_url"], Convert.ToInt64(asset["size"]) };
            }
        }
        catch { return null; }
    }

    // The new exe must be complete, report the advertised version and, if this exe is signed,
    // be signed by the same publisher.
    static bool IsTrustedUpdate(string path, long size, string tag, string currentExe)
    {
        try
        {
            if (new FileInfo(path).Length != size) return false;
            using (FileStream fs = File.OpenRead(path))
                if (fs.ReadByte() != 'M' || fs.ReadByte() != 'Z') return false;
            if (Program.ParseVersion(FileVersionInfo.GetVersionInfo(path).ProductVersion) != Program.ParseVersion(tag)) return false;
            string mine = SignerOf(currentExe);
            return mine == null || mine == SignerOf(path);
        }
        catch { return false; }
    }

    static string SignerOf(string file)
    {
        try { return X509Certificate.CreateFromSignedFile(file).Subject; } catch { return null; }
    }

    static bool CanWriteNextTo(string exe)
    {
        try
        {
            string probe = Path.Combine(Path.GetDirectoryName(exe), ".toolbox-write-test");
            File.WriteAllText(probe, "");
            File.Delete(probe);
            return true;
        }
        catch { return false; }
    }

    // Swaps the exe after this process exits (a running exe can't be overwritten), optionally restarting it.
    void ApplyUpdate(bool relaunch)
    {
        if (updPath == null || !File.Exists(updPath)) return;
        updApplied = true;
        Func<string, string> q = s => "'" + s.Replace("'", "''") + "'";
        string exe = Application.ExecutablePath;
        string script =
            "$ErrorActionPreference='SilentlyContinue'\n" +
            "Wait-Process -Id " + Process.GetCurrentProcess().Id + " -Timeout 60\n" +
            "for ($i = 0; $i -lt 40; $i++) { try { Copy-Item -LiteralPath " + q(updPath) + " -Destination " + q(exe) + " -Force -ErrorAction Stop; break } catch { Start-Sleep -Milliseconds 500 } }\n" +
            "Remove-Item -LiteralPath " + q(updPath) + " -Force\n" +
            (relaunch ? "Start-Process -FilePath " + q(exe) + "\n" : "");
        try
        {
            Process.Start(new ProcessStartInfo("powershell.exe",
                "-NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -EncodedCommand " +
                Convert.ToBase64String(Encoding.Unicode.GetBytes(script)))
            { UseShellExecute = false, CreateNoWindow = true });
            if (relaunch) Close();
        }
        catch { updApplied = false; }
    }

    // ---- helpers ------------------------------------------------------------------------------------

    static bool IsDownload(Uri u)
    {
        string p = u.AbsolutePath.ToLowerInvariant();
        return p.Contains("/releases/download/") ||
               p.EndsWith(".exe") || p.EndsWith(".msi") || p.EndsWith(".zip") || p.EndsWith(".7z") ||
               p.EndsWith(".msixbundle") || p.EndsWith(".msix");
    }

    static void OpenExternal(string target)
    {
        try { Process.Start(new ProcessStartInfo(target) { UseShellExecute = true }); }
        catch { }
    }
}
