# Builds ..\WindowsToolbox.exe - a single portable exe with ..\index.html embedded.
# Uses only the C# compiler that ships with Windows (.NET Framework 4.x).
# WebView2 SDK files go to .\lib (downloaded from the Microsoft.Web.WebView2 NuGet package if missing).
#
#   .\build.ps1                  -> version from the latest git tag + "-dev"
#   .\build.ps1 -Version 1.2.0   -> release build (used by .github/workflows/release.yml)
param(
    [string]$Version = "",
    [string]$Repo = "barnibeats/windows-toolbox"   # repo the app updates from (releases + GitHub Pages)
)
$ErrorActionPreference = "Stop"
$SiteUrl = "https://" + $Repo.Split('/')[0].ToLower() + ".github.io/" + $Repo.Split('/')[1]
$here = $PSScriptRoot
$root = Split-Path $here -Parent
$lib  = Join-Path $here "lib"
$obj  = Join-Path $here "obj"
New-Item -ItemType Directory -Force $obj | Out-Null

if (-not (Test-Path "$lib\Microsoft.Web.WebView2.Core.dll")) {
    Write-Host "Downloading WebView2 SDK from NuGet..."
    New-Item -ItemType Directory -Force $lib | Out-Null
    $ver = (Invoke-RestMethod "https://api.nuget.org/v3-flatcontainer/microsoft.web.webview2/index.json").versions |
        Where-Object { $_ -notmatch '-' } | Select-Object -Last 1
    $pkg = Join-Path $obj "wv2.zip"
    Invoke-WebRequest "https://api.nuget.org/v3-flatcontainer/microsoft.web.webview2/$ver/microsoft.web.webview2.$ver.nupkg" -OutFile $pkg
    Expand-Archive $pkg "$obj\wv2" -Force
    Copy-Item "$obj\wv2\lib\net462\Microsoft.Web.WebView2.Core.dll", "$obj\wv2\lib\net462\Microsoft.Web.WebView2.WinForms.dll", "$obj\wv2\runtimes\win-x64\native\WebView2Loader.dll" $lib
}

# --- icon: four gradient tiles, same as the page logo ---------------------------------
Add-Type -AssemblyName System.Drawing
function New-TilePng([int]$size) {
    $bmp = New-Object System.Drawing.Bitmap $size, $size
    $g = [System.Drawing.Graphics]::FromImage($bmp)
    $g.SmoothingMode = "AntiAlias"; $g.Clear([System.Drawing.Color]::Transparent)
    $pairs = @(@("#7c5cff","#00d4ff"), @("#00d4ff","#3ddc97"), @("#ff4fd8","#7c5cff"), @("#ffb84f","#ff4fd8"))
    $gap = [math]::Max(1, [int]($size * 0.08)); $pad = [int]($size * 0.06)
    $t = [int](($size - 2 * $pad - $gap) / 2); $r = [math]::Max(1, [int]($t * 0.22))
    for ($i = 0; $i -lt 4; $i++) {
        $x = $pad + ($i % 2) * ($t + $gap); $y = $pad + [math]::Floor($i / 2) * ($t + $gap)
        $rect = New-Object System.Drawing.Rectangle $x, $y, $t, $t
        $br = New-Object System.Drawing.Drawing2D.LinearGradientBrush $rect, ([System.Drawing.ColorTranslator]::FromHtml($pairs[$i][0])), ([System.Drawing.ColorTranslator]::FromHtml($pairs[$i][1])), 45
        $p = New-Object System.Drawing.Drawing2D.GraphicsPath
        $d = 2 * $r
        $p.AddArc($x, $y, $d, $d, 180, 90); $p.AddArc($x + $t - $d, $y, $d, $d, 270, 90)
        $p.AddArc($x + $t - $d, $y + $t - $d, $d, $d, 0, 90); $p.AddArc($x, $y + $t - $d, $d, $d, 90, 90)
        $p.CloseFigure(); $g.FillPath($br, $p)
    }
    $g.Dispose()
    $ms = New-Object System.IO.MemoryStream
    $bmp.Save($ms, [System.Drawing.Imaging.ImageFormat]::Png); $bmp.Dispose()
    return ,$ms.ToArray()
}
$sizes = 16, 24, 32, 48, 64, 128, 256
$pngs = $sizes | ForEach-Object { ,(New-TilePng $_) }
$ico = New-Object System.IO.MemoryStream
$w = New-Object System.IO.BinaryWriter $ico
$w.Write([UInt16]0); $w.Write([UInt16]1); $w.Write([UInt16]$sizes.Count)
$offset = 6 + 16 * $sizes.Count
for ($i = 0; $i -lt $sizes.Count; $i++) {
    $s = $sizes[$i]; $b = if ($s -ge 256) { 0 } else { $s }
    $w.Write([byte]$b); $w.Write([byte]$b); $w.Write([byte]0); $w.Write([byte]0)
    $w.Write([UInt16]1); $w.Write([UInt16]32); $w.Write([UInt32]$pngs[$i].Length); $w.Write([UInt32]$offset)
    $offset += $pngs[$i].Length
}
foreach ($p in $pngs) { $w.Write($p) }
$w.Flush(); [System.IO.File]::WriteAllBytes("$obj\app.ico", $ico.ToArray())

# --- version info ----------------------------------------------------------------------
if (-not $Version) {
    $tag = ""
    try { $tag = (git -C $root describe --tags --abbrev=0 2>$null) } catch { }
    if (-not $tag) { $tag = "0.0.0" }
    $Version = ($tag -replace '^v', '') + "-dev"
}
$Version = $Version -replace '^v', ''
$numeric = ([regex]::Match($Version, '^\d+(\.\d+){0,3}')).Value
if (-not $numeric) { $numeric = "0.0.0" }
@"
// Generated by build.ps1 - do not edit.
[assembly: System.Reflection.AssemblyTitle("Windows Toolbox")]
[assembly: System.Reflection.AssemblyProduct("Windows Toolbox")]
[assembly: System.Reflection.AssemblyVersion("$numeric")]
[assembly: System.Reflection.AssemblyFileVersion("$numeric")]
[assembly: System.Reflection.AssemblyInformationalVersion("$Version")]
static class AppInfo
{
    public const string Version = "$Version";
    public const string Repo = "$Repo";
    public const string SiteUrl = "$SiteUrl";
    public const string PageUrl = "$SiteUrl/index.html";
}
"@ | Set-Content -Encoding UTF8 "$obj\AppInfo.cs"

# --- page: validate catalog.json and inline it into dist\index.html --------------------
& node "$root\tools\build.mjs"
if ($LASTEXITCODE -ne 0) { throw "Page build failed (see catalog errors above)" }

# --- compile ---------------------------------------------------------------------------
$csc = "$env:WINDIR\Microsoft.NET\Framework64\v4.0.30319\csc.exe"
$out = Join-Path $root "WindowsToolbox.exe"
$fx  = "$env:WINDIR\Microsoft.NET\Framework64\v4.0.30319"
& $csc /nologo /target:winexe /platform:x64 /optimize+ /out:"$out" /win32icon:"$obj\app.ico" `
    /r:"$fx\System.Windows.Forms.dll" /r:"$fx\System.Drawing.dll" `
    /r:"$fx\System.Core.dll" /r:"$fx\System.Web.Extensions.dll" `
    /r:"$lib\Microsoft.Web.WebView2.Core.dll" /r:"$lib\Microsoft.Web.WebView2.WinForms.dll" `
    /resource:"$lib\Microsoft.Web.WebView2.Core.dll,Microsoft.Web.WebView2.Core.dll" `
    /resource:"$lib\Microsoft.Web.WebView2.WinForms.dll,Microsoft.Web.WebView2.WinForms.dll" `
    /resource:"$lib\WebView2Loader.dll,WebView2Loader.dll" `
    /resource:"$root\dist\index.html,index.html" `
    "$here\Program.cs" "$obj\AppInfo.cs"
if ($LASTEXITCODE -ne 0) { throw "Build failed" }
Write-Host ("Built: {0} v{1} ({2:N1} MB)" -f $out, $Version, ((Get-Item $out).Length / 1MB))
